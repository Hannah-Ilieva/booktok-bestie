CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS works (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    normalized_title TEXT NOT NULL,
    authors TEXT NOT NULL DEFAULT '',
    description TEXT,
    first_publication_year SMALLINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS works_normalized_title_idx
    ON works (normalized_title);

CREATE TABLE IF NOT EXISTS editions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id BIGINT NOT NULL REFERENCES works(id) ON DELETE CASCADE,
    isbn_13 TEXT,
    isbn_10 TEXT,
    publisher TEXT,
    publication_year SMALLINT,
    publication_date DATE,
    format TEXT,
    language_code TEXT,
    page_count INTEGER CHECK (page_count IS NULL OR page_count > 0),
    cover_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS editions_isbn_13_unique
    ON editions (isbn_13)
    WHERE isbn_13 IS NOT NULL AND isbn_13 <> '';

CREATE UNIQUE INDEX IF NOT EXISTS editions_isbn_10_unique
    ON editions (isbn_10)
    WHERE isbn_10 IS NOT NULL AND isbn_10 <> '';

CREATE INDEX IF NOT EXISTS editions_work_id_idx ON editions (work_id);

CREATE TABLE IF NOT EXISTS source_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider TEXT NOT NULL
        CHECK (provider IN ('open_library', 'google_books', 'hardcover')),
    provider_record_id TEXT NOT NULL,
    work_id BIGINT REFERENCES works(id) ON DELETE CASCADE,
    edition_id BIGINT REFERENCES editions(id) ON DELETE CASCADE,
    source_url TEXT,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT source_records_provider_id_unique
        UNIQUE (provider, provider_record_id),

    CONSTRAINT source_records_must_link_to_a_book
        CHECK (work_id IS NOT NULL OR edition_id IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS source_records_work_id_idx
    ON source_records (work_id);
CREATE INDEX IF NOT EXISTS source_records_edition_id_idx
    ON source_records (edition_id);

CREATE TABLE IF NOT EXISTS label_taxonomy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label_type TEXT NOT NULL
        CHECK (label_type IN ('genre', 'trope', 'theme', 'spice')),
    label_key TEXT NOT NULL,
    display_name TEXT NOT NULL,
    spice_level SMALLINT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT label_taxonomy_key_unique UNIQUE (label_type, label_key),
    CONSTRAINT label_taxonomy_spice_level_check CHECK (
        (label_type = 'spice' AND spice_level IS NOT NULL AND spice_level BETWEEN 1 AND 5)
        OR (label_type <> 'spice' AND spice_level IS NULL)
    )
);

CREATE TABLE IF NOT EXISTS work_labels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id BIGINT NOT NULL REFERENCES works(id) ON DELETE CASCADE,
    label_id BIGINT NOT NULL REFERENCES label_taxonomy(id) ON DELETE RESTRICT,
    confidence NUMERIC(4, 3) CHECK (
        confidence IS NULL OR confidence BETWEEN 0 AND 1
    ),
    model_name TEXT,
    model_version TEXT,
    human_verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT work_labels_assignment_unique
        UNIQUE NULLS NOT DISTINCT (work_id, label_id, model_name, model_version)
);

CREATE INDEX IF NOT EXISTS work_labels_work_id_idx ON work_labels (work_id);
CREATE INDEX IF NOT EXISTS work_labels_label_id_idx ON work_labels (label_id);

CREATE TABLE IF NOT EXISTS work_label_corrections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id BIGINT NOT NULL REFERENCES works(id) ON DELETE CASCADE,
    from_label_id BIGINT REFERENCES label_taxonomy(id) ON DELETE SET NULL,
    to_label_id BIGINT REFERENCES label_taxonomy(id) ON DELETE SET NULL,
    changed_by TEXT NOT NULL DEFAULT 'local_user',
    note TEXT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT work_label_correction_changes_value CHECK (
        from_label_id IS DISTINCT FROM to_label_id
    )
);

CREATE INDEX IF NOT EXISTS work_label_corrections_work_id_idx
    ON work_label_corrections (work_id, changed_at DESC);

CREATE TABLE IF NOT EXISTS interaction_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id BIGINT NOT NULL REFERENCES works(id) ON DELETE CASCADE,
    edition_id BIGINT REFERENCES editions(id) ON DELETE SET NULL,
    event_type TEXT NOT NULL CHECK (
        event_type IN ('impression', 'click', 'save', 'skip', 'shelf_add', 'rating')
    ),
    rating NUMERIC(2, 1) CHECK (rating IS NULL OR rating BETWEEN 0 AND 5),
    event_source TEXT NOT NULL DEFAULT 'local_app',
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT interaction_rating_event_check CHECK (
        (event_type = 'rating' AND rating IS NOT NULL)
        OR (event_type <> 'rating' AND rating IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS interaction_events_work_created_idx
    ON interaction_events (work_id, created_at DESC);
CREATE INDEX IF NOT EXISTS interaction_events_type_created_idx
    ON interaction_events (event_type, created_at DESC);
