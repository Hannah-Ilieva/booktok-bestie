CREATE EXTENSION IF NOT EXISTS pg_trgm;

ALTER TABLE label_taxonomy
    ADD COLUMN IF NOT EXISTS description TEXT NOT NULL DEFAULT '';

ALTER TABLE work_labels
    ADD COLUMN IF NOT EXISTS is_current BOOLEAN NOT NULL DEFAULT TRUE;

ALTER TABLE work_label_corrections
    ADD COLUMN IF NOT EXISTS from_confidence NUMERIC(4, 3),
    ADD COLUMN IF NOT EXISTS from_model_name TEXT,
    ADD COLUMN IF NOT EXISTS from_model_version TEXT;

CREATE TABLE IF NOT EXISTS reading_shelf (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id BIGINT NOT NULL REFERENCES works(id) ON DELETE CASCADE,
    edition_id BIGINT REFERENCES editions(id) ON DELETE SET NULL,
    legacy_sqlite_id INTEGER UNIQUE,
    genre TEXT,
    status TEXT NOT NULL DEFAULT 'Want to Read'
        CHECK (status IN ('Want to Read', 'Currently Reading', 'Finished', 'DNF')),
    total_pages INTEGER CHECK (total_pages IS NULL OR total_pages > 0),
    current_page INTEGER NOT NULL DEFAULT 0 CHECK (current_page >= 0),
    rating NUMERIC(2, 1) CHECK (rating IS NULL OR rating BETWEEN 0 AND 5),
    review TEXT,
    mood TEXT,
    tropes TEXT,
    added_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS reading_shelf_status_idx
    ON reading_shelf (status, added_at DESC);
CREATE INDEX IF NOT EXISTS reading_shelf_work_id_idx
    ON reading_shelf (work_id);

CREATE TABLE IF NOT EXISTS work_embeddings (
    work_id BIGINT PRIMARY KEY REFERENCES works(id) ON DELETE CASCADE,
    embedding VECTOR(384) NOT NULL,
    model_name TEXT NOT NULL,
    model_version TEXT NOT NULL,
    content_hash TEXT NOT NULL,
    embedded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS work_embeddings_cosine_idx
    ON work_embeddings USING hnsw (embedding vector_cosine_ops);

CREATE INDEX IF NOT EXISTS works_normalized_title_trgm_idx
    ON works USING gin (normalized_title gin_trgm_ops);

CREATE TABLE IF NOT EXISTS catalog_match_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incoming_work_id BIGINT REFERENCES works(id) ON DELETE SET NULL,
    candidate_work_id BIGINT REFERENCES works(id) ON DELETE SET NULL,
    incoming_title TEXT NOT NULL,
    candidate_title TEXT NOT NULL,
    similarity_score NUMERIC(4, 3) NOT NULL
        CHECK (similarity_score BETWEEN 0 AND 1),
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'kept_separate', 'merged', 'dismissed')),
    decision_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolved_at TIMESTAMPTZ,
    CONSTRAINT catalog_match_not_same_work CHECK (
        incoming_work_id IS NULL OR candidate_work_id IS NULL
        OR incoming_work_id <> candidate_work_id
    ),
    CONSTRAINT catalog_match_pair_unique
        UNIQUE NULLS NOT DISTINCT (incoming_work_id, candidate_work_id)
);

CREATE INDEX IF NOT EXISTS catalog_match_reviews_pending_idx
    ON catalog_match_reviews (created_at DESC)
    WHERE status = 'pending';

